"""Node 4 (software engineer): design.system + product.spec -> code.bundle.

Boring, readable output on purpose. The bundle is hand-written HTML and CSS with
no build step, no framework and no JavaScript, because the job of this page is
to load instantly on a phone in a driveway and to survive being hosted on a
static file server for years.

What this node refuses to do:

  * pick a colour, a size or a spacing value - every one of those comes from the
    design tokens, so a design change is a token change;
  * write copy - every string comes from the product spec;
  * emit a secret - scan_for_secrets() runs over the generated bytes and is a
    hard violation, which is the deterministic stand-in for gitleaks in G4.

The bundle is returned as an in-memory mapping of relative path to text. It
touches no disk, so the renderer is trivially testable and the deployment node
stays the only thing in the pipeline that writes files.
"""

